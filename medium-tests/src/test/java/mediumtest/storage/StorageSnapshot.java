package mediumtest.storage;

import java.io.IOException;
import java.io.Reader;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Properties;
import java.util.stream.Collectors;
import org.flywaydb.core.internal.license.VersionPrinter;
import org.jooq.DSLContext;

/**
 * A copy of the local storage written by a released version of SonarLint Core, see storage-snapshots/README.md.
 * <p>
 * Shared by {@link StorageSnapshotGeneratorMediumTests}, which runs on the release tag to produce a snapshot, and {@link StorageUpgradeMediumTests}, which opens it with
 * the current code. Keep the generator and this class free of test APIs that previous releases do not have, so they still compile on the tag.
 */
final class StorageSnapshot {

  static final String CONNECTION_ID = "conn1";
  static final String PROJECT_KEY = "projectKey";
  static final String CONFIG_SCOPE_ID = "configScope";

  static final String METADATA_FILE = "snapshot.properties";
  static final String SCHEMA_FILE = "schema.sql";
  private static final String SNAPSHOTS_RESOURCE = "/storage-snapshots";
  private static final String FLYWAY_HISTORY_TABLE = "flyway_schema_history";
  private static final String MIGRATION_PREFIX = "migration.";
  private static final String ROWS_PREFIX = "rows.";

  record Metadata(String release, String h2Version, String flywayVersion, Map<String, Integer> checksumsByMigration, Map<String, Integer> rowsByTable) {

    static Metadata of(String release, DSLContext dsl) {
      return new Metadata(release, StorageSnapshot.h2Version(dsl), VersionPrinter.getVersion(), StorageSnapshot.migrationChecksums(dsl), StorageSnapshot.rowCounts(dsl));
    }

    static Metadata read(Path snapshotDirectory) throws IOException {
      var properties = new Properties();
      try (Reader reader = Files.newBufferedReader(snapshotDirectory.resolve(METADATA_FILE), StandardCharsets.UTF_8)) {
        properties.load(reader);
      }
      return new Metadata(properties.getProperty("release"), properties.getProperty("h2"), properties.getProperty("flyway"),
        withPrefix(properties, MIGRATION_PREFIX), withPrefix(properties, ROWS_PREFIX));
    }

    void write(Path snapshotDirectory) throws IOException {
      // Written by hand rather than with Properties.store(), which adds a timestamp and does not keep the order
      var content = new StringBuilder()
        .append("# Generated by StorageSnapshotGeneratorMediumTests, do not edit\n")
        .append("release=").append(release).append('\n')
        .append("h2=").append(h2Version).append('\n')
        .append("flyway=").append(flywayVersion).append('\n');
      checksumsByMigration.forEach((version, checksum) -> content.append(MIGRATION_PREFIX).append(version).append('=').append(checksum).append('\n'));
      rowsByTable.forEach((table, rows) -> content.append(ROWS_PREFIX).append(table).append('=').append(rows).append('\n'));
      Files.writeString(snapshotDirectory.resolve(METADATA_FILE), content, StandardCharsets.UTF_8);
    }

    private static Map<String, Integer> withPrefix(Properties properties, String prefix) {
      return properties.stringPropertyNames().stream()
        .filter(name -> name.startsWith(prefix))
        .collect(Collectors.toMap(name -> name.substring(prefix.length()), name -> Integer.parseInt(properties.getProperty(name))));
    }
  }

  private StorageSnapshot() {
    // utility class
  }

  /**
   * There is only one snapshot at a time: the one written by the latest release.
   */
  static Path latestSnapshotDirectory() throws IOException, URISyntaxException {
    var snapshotsRoot = Path.of(StorageSnapshot.class.getResource(SNAPSHOTS_RESOURCE).toURI());
    try (var children = Files.list(snapshotsRoot)) {
      var snapshots = children.filter(Files::isDirectory).toList();
      if (snapshots.size() != 1) {
        throw new IllegalStateException("Expected exactly one storage snapshot in " + snapshotsRoot + " but found " + snapshots);
      }
      return snapshots.get(0);
    }
  }

  static String h2Version(DSLContext dsl) {
    return dsl.fetchSingle("SELECT H2VERSION()").get(0, String.class);
  }

  /**
   * Successfully applied versioned migrations, in the order they were applied
   */
  static Map<String, Integer> migrationChecksums(DSLContext dsl) {
    var checksums = new LinkedHashMap<String, Integer>();
    dsl.fetch("SELECT \"version\", \"checksum\" FROM \"" + FLYWAY_HISTORY_TABLE + "\" WHERE \"success\" AND \"version\" IS NOT NULL ORDER BY \"installed_rank\"")
      .forEach(rec -> checksums.put(rec.get(0, String.class), rec.get(1, Integer.class)));
    return checksums;
  }

  static Map<String, Integer> rowCounts(DSLContext dsl) {
    var counts = new LinkedHashMap<String, Integer>();
    dsl.fetch("SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME <> ? ORDER BY TABLE_NAME",
      FLYWAY_HISTORY_TABLE)
      .getValues(0, String.class)
      .forEach(table -> counts.put(table, dsl.fetchSingle("SELECT COUNT(*) FROM \"" + table + "\"").get(0, Integer.class)));
    return counts;
  }

  /**
   * A text version of the schema, so that changes are visible when reviewing a new snapshot
   */
  static String schemaScript(DSLContext dsl) {
    return dsl.fetch("SCRIPT NODATA").getValues(0, String.class).stream()
      // Drop the user definition and the row count estimates, which are not part of the schema
      .filter(line -> !line.startsWith("CREATE USER") && !line.startsWith("-- "))
      .collect(Collectors.joining("\n", "", "\n"));
  }
}
